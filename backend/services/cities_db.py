"""
US Cities database for Alert Dashboard V2 broadcast graphics.

Priority order for data source:
  1. backend/data/us_cities.csv  (from download_cities.py — ~10K cities)
  2. Bundled fallback              (~1,600 carefully selected cities)

Bundled data focuses on:
  - All 50 state capitals
  - All US cities > 100K population
  - Comprehensive coverage of tornado/severe-weather-prone states
  - County seats and key reference towns for Great Plains / Dixie Alley
"""

import csv
import logging
from functools import lru_cache
from pathlib import Path

logger = logging.getLogger(__name__)

_CSV_PATH = Path(__file__).parent.parent / "data" / "us_cities.csv"

# (city_name, state_abbr, lat, lon, population)
CityEntry = tuple[str, str, float, float, int]


@lru_cache(maxsize=1)
def get_cities() -> list[CityEntry]:
    """Return all cities. Result is cached after first call."""
    if _CSV_PATH.exists():
        try:
            cities = _load_csv(_CSV_PATH)
            if cities:
                logger.info("Cities DB: loaded %d cities from %s", len(cities), _CSV_PATH)
                return cities
        except Exception as exc:
            logger.warning("Cities DB: CSV load failed (%s), using bundled data", exc)
    logger.info("Cities DB: using bundled dataset (%d cities)", len(_BUNDLED))
    return list(_BUNDLED)


def _load_csv(path: Path) -> list[CityEntry]:
    cities: list[CityEntry] = []
    with open(path, encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            try:
                name = (row.get("city") or row.get("city_ascii") or row.get("name") or "").strip()
                state = (row.get("state_id") or row.get("state_abbr") or row.get("admin1") or "").strip().upper()[:2]
                lat = float(row.get("lat") or row.get("latitude") or 0)
                lon = float(row.get("lng") or row.get("lon") or row.get("longitude") or 0)
                pop = int(float(row.get("population") or 0))
                if name and state and lat and lon:
                    cities.append((name, state, lat, lon, pop))
            except (ValueError, KeyError, TypeError):
                continue
    return cities


